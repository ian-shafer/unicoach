/**
 * `protoc --java_out` over `src/main/proto` (RFC 265). The `.proto` is the
 * reviewed artifact; the Java is build output and is never committed.
 *
 * ONE VERSION, CHECKED (D-G). protoc comes from the dev shell (`flake.nix`) and
 * the runtime from the version catalog, two pins nothing else ties together.
 * Code generated by one protoc and run on another runtime is refused at class
 * load, far from the cause, so this task compares the two first and fails the
 * build naming both. The protoc it requires is derived from the catalog's
 * runtime version, never written a second time.
 */
abstract class GenerateProto : DefaultTask() {
  @get:InputDirectory
  @get:PathSensitive(PathSensitivity.RELATIVE)
  abstract val protoDir: DirectoryProperty

  @get:OutputDirectory
  abstract val outputDir: DirectoryProperty

  /** The protobuf Java runtime version from the catalog: `4.<protoc version>`. */
  @get:Input
  abstract val runtimeVersion: Property<String>

  @get:Inject
  abstract val execOperations: ExecOperations

  @TaskAction
  fun generate() {
    requireMatchingProtoc()
    runProtoc(freshOutputDir())
  }

  /** Fails the build, naming both versions, when protoc on PATH is not the one the runtime pairs with. */
  private fun requireMatchingProtoc() {
    // The Java runtime is versioned `<runtime major>.<protoc version>` (4.34.1
    // pairs with protoc 34.1), so the protoc this build needs is the catalog
    // version with its leading component dropped.
    val runtime = runtimeVersion.get()
    val requiredProtoc = runtime.substringAfter('.')
    val actualProtoc = installedProtocVersion()
    if (actualProtoc != requiredProtoc) {
      throw GradleException(
        "protoc on PATH is [$actualProtoc] but the protobuf runtime in gradle/libs.versions.toml is " +
          "[$runtime], which needs protoc [$requiredProtoc]; bump one to match the other",
      )
    }
  }

  /** The version protoc on PATH reports, without its `libprotoc ` prefix. */
  private fun installedProtocVersion(): String {
    val reported = ByteArrayOutputStream()
    execOperations.exec {
      commandLine("protoc", "--version")
      standardOutput = reported
    }
    return reported.toString().trim().removePrefix("libprotoc ")
  }

  /** The output directory, emptied: a `.proto` removed since the last run leaves no stale class behind. */
  private fun freshOutputDir(): File =
    outputDir.get().asFile.also {
      it.deleteRecursively()
      it.mkdirs()
    }

  /** One protoc invocation over every `.proto`, in a stable order. */
  private fun runProtoc(out: File) {
    val protos =
      protoDir.asFileTree
        .matching { include("**/*.proto") }
        .files
        .map { it.path }
        .sorted()
    execOperations.exec {
      commandLine(listOf("protoc", "--proto_path=${protoDir.get().asFile.path}", "--java_out=${out.path}") + protos)
    }
  }
}

val generateProto =
  tasks.register<GenerateProto>("generateProto") {
    protoDir.set(layout.projectDirectory.dir("src/main/proto"))
    outputDir.set(layout.buildDirectory.dir("generated/sources/proto/main/java"))
    runtimeVersion.set(libs.versions.protobuf)
  }

sourceSets.main {
  java.srcDir(generateProto.flatMap { it.outputDir })
}

tasks.compileJava { dependsOn(generateProto) }
tasks.compileKotlin { dependsOn(generateProto) }
